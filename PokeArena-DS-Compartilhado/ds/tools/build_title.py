#!/usr/bin/env python3
"""Assemble the title screen and export its indexed DS bitmap and RGB555 palette."""
from pathlib import Path

from PIL import Image, ImageOps


def main():
    ds = Path(__file__).resolve().parents[1]
    with Image.open(ds / 'assets/title-route.png') as original:
        screen = ImageOps.fit(original.convert('RGBA'), (256, 192), Image.Resampling.LANCZOS)
    with Image.open(ds / 'assets/title-logo.png') as original:
        logo = original.convert('RGBA')
        bounds = logo.getbbox(alpha_only=True)
        if bounds is None or logo.getchannel('A').getextrema()[0] != 0:
            raise ValueError('The title logo needs visible art and a transparent background')
        logo = ImageOps.contain(logo.crop(bounds), (138, 94), Image.Resampling.LANCZOS)
    screen.alpha_composite(logo, ((screen.width - logo.width) // 2, 10))
    # The logo stays above row 104. HUD and animated sprites use the palette gaps.
    palette_start, sprite_palette_start = 48, 224
    color_count = sprite_palette_start - palette_start
    indexed = screen.convert('RGB').quantize(colors=color_count, dither=Image.Dither.NONE)
    rgb = indexed.getpalette()[:color_count * 3]
    colors = [(r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
              for r, g, b in zip(rgb[::3], rgb[1::3], rgb[2::3])]

    def rows(values, count):
        return '\n'.join('    ' + ','.join(hex(v) for v in values[i:i + count]) + ','
                         for i in range(0, len(values), count))

    pixels = [palette_start + index for index in indexed.tobytes()]
    generated = ('/* Generated by tools/build_title.py. */\n'
                 f'enum {{ TITLE_ART_PALETTE={palette_start}, TITLE_SPRITE_PALETTE={sprite_palette_start} }};\n'
                 'static const uint16_t titlePalette[] = {\n' + rows(colors, 12) + '\n};\n'
                 'static const uint8_t titlePixels[256*192] = {\n' + rows(pixels, 24) + '\n};\n')
    (ds / 'source/generated_title.inc').write_text(generated, encoding='ascii')


if __name__ == '__main__':
    main()
