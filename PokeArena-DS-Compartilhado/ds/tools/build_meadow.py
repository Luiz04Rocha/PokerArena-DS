"""Paint the native battle meadow in a sixteen-color pixel art palette."""

import math
from pathlib import Path
import random

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[2]
WIDTH, HEIGHT = 256, 128
CENTER_X, CENTER_Y = 128, 120
RIM_X, RIM_Y = 113, 76
COLORS = [
    (44, 85, 70), (60, 111, 78), (79, 133, 86), (97, 150, 94),
    (111, 161, 98), (125, 169, 105), (143, 180, 115), (145, 163, 105),
    (161, 174, 115), (174, 179, 122), (192, 188, 133), (97, 115, 99),
    (127, 140, 112), (154, 163, 132), (180, 186, 148), (202, 202, 167),
]


def clamp(value):
    return max(0, min(1, value))


def world_pixel(x, y):
    return round((x + 64) * WIDTH / 384), round((y + 60) * HEIGHT / 330)


def rim_distance(x, y):
    return math.hypot((x - CENTER_X) / RIM_X, (y - CENTER_Y) / RIM_Y)


def entry_x(y):
    return CENTER_X + 8 * math.sin((y - 36) * .023)


def paint_ground(rng):
    image = Image.new('RGB', (WIDTH, HEIGHT))
    pixels = image.load()
    for y in range(HEIGHT):
        for x in range(WIDTH):
            wx, wy = x * 384 / WIDTH - 64, y * 330 / HEIGHT - 60
            rim = rim_distance(wx, wy)
            waves = math.sin(wx * .035 + math.sin(wy * .046)) + math.sin(wy * .052 - wx * .019)
            patch = math.sin(wx * .075 + wy * .057) * math.cos(wy * .089 - wx * .035)
            grass = (108 + 7 * waves, 154 + 6 * waves, 96 + 3 * waves)
            soil = (156 + 5 * waves, 173 + 3 * waves, 116 + 2 * waves)
            worn = clamp((1.09 - rim + patch * .045) * 3.2) * .82
            path = clamp(1 - abs(wx - entry_x(wy)) / 17)
            worn = max(worn, path * clamp((rim - .78) * 5) * .85)
            # Keep texture variation subtle underneath moving sprites and effects.
            noise = rng.uniform(-2.5, 2.5)
            pixels[x, y] = tuple(round(g + (s - g) * worn + noise) for g, s in zip(grass, soil))
    return image


def paint_rim(draw, rng):
    for i in range(116):
        angle = i * math.tau / 116
        spread = rng.uniform(-2.4, 2.4)
        wx = CENTER_X + math.cos(angle) * (RIM_X + spread)
        wy = CENTER_Y + math.sin(angle) * (RIM_Y + spread)
        if abs(wx - entry_x(wy)) < 13 or rng.random() < .12:
            continue
        x, y = world_pixel(wx, wy)
        width = rng.choice((1, 2, 2, 3))
        draw.line((x - 1, y + 1, x + width, y + 1), fill=COLORS[11])
        draw.line((x, y, x + width, y), fill=COLORS[rng.choice((12, 13, 14, 14))])
        if width > 1:
            draw.line((x, y - 1, x + width - 1, y - 1), fill=COLORS[15 if i % 4 == 0 else 14])
        if i % 3 == 0:
            draw.point((x - 2, y - 1), fill=COLORS[7])

    # Flat gravel is concentrated at the openings and scattered just inside the rim.
    for _ in range(75):
        wy = rng.choice((rng.uniform(38, 67), rng.uniform(173, 204)))
        wx = entry_x(wy) + rng.uniform(-12, 12)
        x, y = world_pixel(wx, wy)
        draw.line((x, y, x + rng.randrange(2), y), fill=COLORS[rng.choice((7, 9, 12, 13, 14))])


def paint_turf(draw, rng):
    # Small grouped blades frame the clearing; the center is left quiet for the fight.
    for _ in range(620):
        wx, wy = rng.uniform(-60, 318), rng.uniform(-55, 266)
        rim = rim_distance(wx, wy)
        if rim < .91 or abs(wx - entry_x(wy)) < 16:
            continue
        x, y = world_pixel(wx, wy)
        base = rng.choice((2, 3, 3, 4, 5))
        draw.line((x - 1, y, x + 1, y), fill=COLORS[base])
        if rim > 1.05 and rng.random() < .5:
            draw.point((x, y - 1), fill=COLORS[base])
            draw.point((x + 2, y - 1), fill=COLORS[base + 1])
        if rim < 1.15 and rng.random() < .16:
            draw.point((x + 2, y + 1), fill=COLORS[13])


def main():
    rng = random.Random(4217)
    image = paint_ground(rng)
    draw = ImageDraw.Draw(image)
    paint_turf(draw, rng)
    paint_rim(draw, rng)
    palette = Image.new('P', (1, 1))
    palette.putpalette([channel for color in COLORS for channel in color] + [0] * 720)
    indexed = image.quantize(palette=palette, dither=Image.Dither.NONE)
    indices = list(indexed.get_flattened_data())
    assert max(indices) < len(COLORS)
    words = [sum(indices[i + k] << (k * 4) for k in range(4)) for i in range(0, len(indices), 4)]
    colors = [(r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10) for r, g, b in COLORS]
    lines = [
        '/* Generated by build_meadow.py. Original clearing material. */',
        '#include <stdint.h>',
        'const uint16_t meadow_palette[16] = {' + ','.join(hex(c) for c in colors) + '};',
        'const uint16_t native_meadow[8192] __attribute__((aligned(4))) = {',
    ]
    for i in range(0, len(words), 16):
        lines.append(','.join(hex(w) for w in words[i:i + 16]) + ',')
    lines.append('};')
    (ROOT / 'ds/source/generated_meadow.c').write_text('\n'.join(lines) + '\n', encoding='ascii')

    out = ROOT / 'docs/capturas-v0.28'
    out.mkdir(exist_ok=True)
    indexed.convert('RGB').resize((768, 384), Image.Resampling.NEAREST).save(out / 'material-clareira.png')
    print('Native clearing material: 256x128, 16384 bytes, sixteen colors')


if __name__ == '__main__':
    main()
