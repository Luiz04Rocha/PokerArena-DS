"""Author the native 128x64 scenery atlas in a consistent pixel-art palette.

Original art: two rounded boulders, timber fence, lantern and fallen log.
Cells are anchored at their bottom edge for the native 2.5D billboard renderer.
"""
from pathlib import Path
import random
from PIL import Image,ImageDraw

ROOT=Path(__file__).resolve().parents[2]
PAL=[(0,0,0),(34,47,57),(61,79,88),(86,105,112),(123,141,142),
     (162,178,171),(199,207,183),(76,55,40),(114,78,45),(153,112,62),
     (193,151,85),(223,188,119),(58,104,64),(103,151,80),
     (250,218,137),(255,243,192)]
atlas=Image.new('P',(128,64));atlas.putpalette([v for c in PAL for v in c]+[0]*720)
for variant in range(2):
    im=Image.new('P',(32,32));d=ImageDraw.Draw(im)
    if variant==0:
        edge=[(2,23),(3,15),(8,9),(18,7),(26,11),(30,19),(28,28),(22,31),(7,30)]
        top=[(4,17),(9,11),(18,9),(25,13),(26,18),(18,22),(9,21)]
    else:
        edge=[(4,24),(5,13),(10,5),(20,4),(26,10),(28,23),(25,29),(18,31),(8,30)]
        top=[(7,15),(11,7),(19,6),(24,11),(23,17),(15,20)]
    d.polygon(edge,fill=2,outline=1);d.polygon(top,fill=5)
    d.line(top[:3],fill=6,width=1)
    d.polygon([(7,23),(16,25),(25,21),(25,27),(19,29),(9,28)],fill=3)
    d.line([(15,12),(13,17),(17,20),(16,24)],fill=3,width=1)
    d.line([(18,22),(22,20),(25,21)],fill=4,width=1)
    rng=random.Random(214+variant)
    for _ in range(24):
        x,y=rng.randrange(5,27),rng.randrange(10,28)
        if im.getpixel((x,y)) in (3,5):d.point((x,y),fill=4)
    d.line([(5,27),(9,28),(11,27)],fill=12,width=2)
    d.line([(7,27),(10,27)],fill=13,width=1)
    d.line([(24,27),(25,29),(22,30)],fill=12,width=2)
    atlas.paste(im,(variant*32,0))

# Chamfered posts, two rails, grain, caps and small metal fasteners.
im=Image.new('P',(32,32));d=ImageDraw.Draw(im)
for y in (12,22):
    d.rectangle((0,y,31,y+4),fill=1);d.rectangle((0,y,31,y+2),fill=9)
    d.line((0,y,31,y),fill=11);d.line((0,y+3,31,y+3),fill=7)
    d.line((10,y+1,19,y+1),fill=10)
for x in (3,):
    d.polygon([(x-2,8),(x,5),(x+3,5),(x+5,8),(x+5,30),(x-2,30)],fill=1)
    d.rectangle((x-1,9,x+3,29),fill=9);d.line((x-1,9,x-1,28),fill=11)
    d.line((x+3,10,x+3,29),fill=7);d.line((x+1,16,x+1,23),fill=8)
    d.polygon([(x-2,8),(x,6),(x+3,6),(x+5,8)],fill=11)
    for y in (13,23):d.point((x+1,y),fill=2)
atlas.paste(im,(64,0))

# Lantern: cool metal frame and warm emissive glass.
im=Image.new('P',(32,32));d=ImageDraw.Draw(im)
d.ellipse((8,28,24,31),fill=2);d.rectangle((14,12,18,29),fill=1)
d.line((15,13,15,28),fill=4);d.line((18,13,18,29),fill=2)
d.polygon([(9,5),(15,1),(18,1),(24,5)],fill=1);d.line((11,4,21,4),fill=4)
d.rectangle((11,6,22,14),fill=1);d.rectangle((13,7,20,12),fill=14)
d.rectangle((14,7,16,11),fill=15);d.line((18,6,18,13),fill=8)
d.rectangle((10,14,23,15),fill=2);d.line((12,15,21,15),fill=4)
atlas.paste(im,(96,0))

im=Image.new('P',(64,32));d=ImageDraw.Draw(im)
d.polygon([(6,20),(12,12),(52,13),(59,19),(55,29),(11,31),(5,27)],fill=1)
d.polygon([(10,17),(16,14),(51,15),(54,20),(50,28),(13,29)],fill=8)
d.line((15,16,50,17),fill=10,width=2);d.line((17,21,49,22),fill=7,width=2)
d.line((23,26,46,27),fill=9,width=1)
d.ellipse((4,17,17,30),fill=7);d.ellipse((5,17,16,28),fill=11)
d.ellipse((8,20,14,26),outline=9);d.point((11,23),fill=8)
d.line((29,16,36,16),fill=12,width=2);d.point((33,15),fill=13)
atlas.paste(im,(0,32))

indices=list(atlas.get_flattened_data());assert max(indices)<16
words=[sum(indices[i+k]<<(k*4) for k in range(4)) for i in range(0,len(indices),4)]
colors=[(r>>3)|((g>>3)<<5)|((b>>3)<<10) for r,g,b in PAL]
lines=['/* Original scenery atlas generated by tools/build_props.py. */','#include <stdint.h>',
       'const uint16_t props_palette[16]={'+','.join(hex(c) for c in colors)+'};',
       'const uint16_t props_atlas[2048] __attribute__((aligned(4)))={']
for i in range(0,len(words),16):lines.append(','.join(hex(w) for w in words[i:i+16])+',')
lines.append('};')
(ROOT/'ds/source/generated_props.c').write_text('\n'.join(lines)+'\n',encoding='utf-8')
out=ROOT/'docs/capturas-v0.11';out.mkdir(exist_ok=True)
preview=atlas.convert('RGBA');preview.putalpha(Image.frombytes('L',atlas.size,atlas.tobytes()).point(lambda c:255 if c else 0))
preview.resize((768,384),Image.Resampling.NEAREST).save(out/'detalhes-cenario.png')
print('Original scenery atlas: 128x64, 16 colors, 4096 bytes')
